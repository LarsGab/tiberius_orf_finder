#!/bin/bash
# Step 1 of the training-species protein pipeline.
#
# For each of the 68 vertebrate training species:
#   1. Extract Tiberius ab initio peptides (from tiberius/tiberius_seqlen.gtf).
#   2. Diamond blastp peptides vs. the order-excluded ODB to rank protein donor species.
#   3. Extract proteins from the top-4 closest species → protein_top4.fa.
#
# The ODB is never written to disk: the order-exclusion set is computed once
# (BFS on nodes.dmp), embedded into a temp Python filter script on /tmp, and
# used to stream Vertebrata.fa.gz directly into diamond makedb and protein
# extraction.  Two read passes over the shared ODB instead of 68 per-species gz
# copies.
#
# Requires:
#   results/training_vertebrates_v2/species_order_taxids.tsv
#   (generated by: python scripts/lookup_order_taxids.py ... )
#
# Output per species (${RESULTS_DIR}/${species}/proteins/):
#   tiberius_peptides.fa          gffread extraction from tiberius_seqlen.gtf
#   diamond_db.dmnd               Diamond DB built from order-excluded ODB stream
#   diamond_hits.tsv              blastp output
#   species_rank.tsv              all species ranked by total bitscore
#   top_species.txt               top-4 species taxids (one per line)
#   protein_top4.fa               proteins from those 4 species
#
#SBATCH --job-name=prep_prot_train
#SBATCH --partition=snowball,pinky,batch
#SBATCH --cpus-per-task=16
#SBATCH --mem=64G
#SBATCH --time=24:00:00
#SBATCH --array=0-67%10
#SBATCH --output=/projects/AI-GUSTUS/tiberius_orf_finder/logs/prep_prot_train_%A_%a.out
#SBATCH --error=/projects/AI-GUSTUS/tiberius_orf_finder/logs/prep_prot_train_%A_%a.err

set -euo pipefail
source /etc/profile.d/modules.sh
module load singularity/3.11.3

PROJDIR=/projects/AI-GUSTUS/tiberius_orf_finder
RESULTS_DIR=${PROJDIR}/results/training_vertebrates_v2
ODB_GZ=/home/gabriell/tiberius_proteins_analysis/odb/raw/Vertebrata.fa.gz
NODES_DMP=/home/gabriell/tiberius_proteins_analysis/odb/nodes.dmp
TIBERIUS_REPO=/home/gabriell/Tiberius
TAXIDS_TSV=${RESULTS_DIR}/species_order_taxids.tsv
SIF=${PROJDIR}/sif/tiberius_2.0.2.sif
TOP_N=4
CPUS=${SLURM_CPUS_PER_TASK:-16}

mkdir -p "${PROJDIR}/logs"

declare -a SPECIES=(
    "Acipenser_ruthenus"
    "Alligator_mississippiensis"
